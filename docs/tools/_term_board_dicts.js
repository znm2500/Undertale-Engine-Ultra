let total = 0;
for (const [name, pairs] of Object.entries(PLANS)) {
  const p = path.join(T, name);
  let s = fs.readFileSync(p, 'utf8');
  let n = 0;
  for (const [a, b] of pairs) {
    const c = s.split(a).length - 1;
    if (c) { s = s.split(a).join(b); n += c; }
  }
  fs.writeFileSync(p, s, { encoding: 'utf8' });
  total += n;
  // 残留扫描（含 UI 语境也打出来人工过目）
  const left = (s.match(/.{0,18}面板.{0,18}/g) || []).filter(x => !x.includes('面板中心到')); // 参数已改，不会命中
  console.log(name.padEnd(16), 'replaced:', String(n).padStart(2), '| 残留「面板」:', left.length ? left.length + ' 处' : '无');
}
console.log('total replacements:', total);
